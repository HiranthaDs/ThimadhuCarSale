import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
const base=process.env.TEST_URL || 'http://127.0.0.1:5174';
await mkdir('.audit',{recursive:true});
const browser=process.env.CDP_URL ? await chromium.connectOverCDP(process.env.CDP_URL) : await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const page=await context.newPage();
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
await page.goto(base,{waitUntil:'domcontentloaded'});
await page.waitForTimeout(1600);
await page.screenshot({path:'.audit/react-desktop.png'});
await page.evaluate(async()=>{for(let y=0;y<document.body.scrollHeight;y+=600){window.scrollTo({top:y,behavior:'instant'});await new Promise(r=>setTimeout(r,100));}window.scrollTo({top:0,behavior:'instant'});});
await page.waitForTimeout(800);
await page.screenshot({path:'.audit/react-full.png',fullPage:true});
const results=[];
const routes=['/','/all-vehicles.html','/car-details.html','/aboutus.html','/services.html','/reviews.html','/sell-your-vehicle-sri-lanka.html','/vehicle-sourcing-sri-lanka.html','/vehicle-information-support.html','/404.html'];
for(const width of [320,390,768,1440]){
  await page.setViewportSize({width,height:width<600?844:1000});
  for(const route of routes){
    await page.goto(`${base}${route}`,{waitUntil:'domcontentloaded'});
    await page.waitForTimeout(350);
    const data=await page.evaluate(()=>({title:document.title,headings:document.querySelectorAll('h1').length,overflow:document.documentElement.scrollWidth>innerWidth+1,body:document.body.innerText.slice(0,100),brokenImages:[...document.querySelectorAll('img')].filter(i=>i.complete&&!i.naturalWidth&&!i.loading).map(i=>i.src)}));
    results.push({width,route,...data});
    if(width===390 && ['/','/services.html','/all-vehicles.html','/sell-your-vehicle-sri-lanka.html'].includes(route))await page.screenshot({path:`.audit/react-${route==='/'?'home':route.slice(1,-5)}-mobile.png`});
  }
}
await page.setViewportSize({width:390,height:844});
await page.goto(base,{waitUntil:'domcontentloaded'});
await page.getByRole('button',{name:'Open menu',exact:true}).click();
await page.getByRole('navigation',{name:'Mobile navigation'}).getByRole('link',{name:/Our services/}).click();
await page.waitForURL('**/services.html');
await page.getByRole('button',{name:'Open menu',exact:true}).waitFor();
const menuNavigates=await page.getByRole('button',{name:'Open menu',exact:true}).isVisible();
await page.goto(base,{waitUntil:'domcontentloaded'});
await page.getByRole('button',{name:'Open menu',exact:true}).click();
await page.keyboard.press('Escape');
const menuEscape=await page.getByRole('button',{name:'Open menu',exact:true}).evaluate(node=>node===document.activeElement);
await page.locator('#home-search').fill('Toyota');
await page.locator('.home-search button').click();
await page.waitForURL('**/all-vehicles.html?q=Toyota');
const searchNavigates=true;
await page.goto(base,{waitUntil:'domcontentloaded'});
await page.getByRole('combobox',{name:'Choose your vehicle journey'}).selectOption({label:'Sell your vehicle'});
const mobileJourney=await page.getByRole('tabpanel').getByRole('link',{name:'Start selling your vehicle',exact:true}).isVisible();
await page.setViewportSize({width:1440,height:1000});
await page.getByRole('tab',{name:'Sell your vehicle',exact:true}).click();
const tabChanges=await page.getByRole('tabpanel').getByRole('link',{name:'Start selling your vehicle'}).isVisible();
await page.getByRole('tab',{name:'Sell your vehicle',exact:true}).focus();
await page.keyboard.press('ArrowRight');
const tabKeyboard=await page.getByRole('tab',{name:'Find something specific',exact:true}).getAttribute('aria-selected')==='true';
await page.locator('.faq-list summary').first().click();
const faqWorks=await page.locator('.faq-list details').first().getAttribute('open')!==null;
const report={results,errors,interactions:{menuNavigates,menuEscape,searchNavigates,mobileJourney,tabChanges,tabKeyboard,faqWorks}};
await writeFile('.audit/browser-report.json',JSON.stringify(report,null,2));
console.log(JSON.stringify({pagesChecked:results.length,layoutFailures:results.filter(r=>r.overflow||r.headings!==1),errors,interactions:report.interactions},null,2));
await context.close();
await browser.close();
if(errors.length||results.some(r=>r.overflow||r.headings!==1)||Object.values(report.interactions).some(v=>!v))process.exitCode=1;
