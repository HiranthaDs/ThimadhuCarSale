import assert from 'node:assert/strict';
import {chromium,expect} from '@playwright/test';
const base=process.env.TEST_URL||'http://127.0.0.1:5174';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
try {
  await page.goto(base,{waitUntil:'domcontentloaded'});
  const video=page.locator('.hs-video');
  await expect.poll(()=>video.evaluate(n=>n.readyState)).toBeGreaterThanOrEqual(2);
  assert.ok((await video.getAttribute('src')).endsWith('/Videos/hero1.mp4'));
  await expect.poll(()=>video.evaluate(n=>n.paused)).toBe(false);
  await page.getByRole('button',{name:'Pause hero video',exact:true}).click();
  await expect.poll(()=>video.evaluate(n=>n.paused)).toBe(true);
  await page.getByRole('button',{name:'Play hero video',exact:true}).click();
  await expect.poll(()=>video.evaluate(n=>n.paused)).toBe(false);
  const scroll=async fraction=>{await page.locator('.hs-story').evaluate((n,p)=>scrollTo({top:(n.offsetHeight-innerHeight)*p,behavior:'instant'}),fraction);await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));};
  await scroll(.3);
  const firstTransform=await page.locator('.hs-phone-scene').evaluate(n=>getComputedStyle(n).transform);
  await scroll(.8);
  assert.notEqual(firstTransform,await page.locator('.hs-phone-scene').evaluate(n=>getComputedStyle(n).transform));
  await expect.poll(()=>video.evaluate(n=>n.paused)).toBe(true);
  const screen=page.locator('.hs-phone-scene .hs-screen-body');
  const original=await screen.getAttribute('class');
  await expect.poll(()=>screen.getAttribute('class'),{timeout:7000}).not.toBe(original);
  await page.locator('.hs-phone-scene').getByRole('button',{name:'Preview sell your vehicle',exact:true}).click();
  await expect(screen).toHaveClass(/hs-screen-page-1/);
  await page.waitForTimeout(5400);
  await expect(screen).toHaveClass(/hs-screen-page-1/);
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto(base,{waitUntil:'domcontentloaded'});
  assert.equal(await video.getAttribute('src'),null);
  await page.getByRole('button',{name:'Play hero video',exact:true}).click();
  await expect.poll(()=>video.evaluate(n=>n.paused)).toBe(false);
  await page.getByRole('button',{name:'Pause hero video',exact:true}).click();
  await expect.poll(()=>video.evaluate(n=>n.paused)).toBe(true);
  assert.deepEqual(errors,[]);
  console.log('PASS: supplied hero video playback/pause, scroll-driven 3D transforms, offscreen video pause, automatic phone navigation, interaction pause, and explicit reduced-motion playback.');
} finally {await browser.close();}
